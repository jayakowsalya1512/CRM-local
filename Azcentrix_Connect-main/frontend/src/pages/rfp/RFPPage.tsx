type Keyword = {
  key: string
  name: string
  aliases: string[]
  category: string
  prompt_hint: string
  active: boolean
  is_default: boolean
}

type SalesSection = {
  field?: string
  value?: string
  page_ref?: string
  values?: string[]
  title?: string
  final_answer?: string
  answer?: string
  key_values?: string[]
  details?: string[]
  pages?: Array<number | string> | string
  confidence?: 'High' | 'Medium' | 'Low' | string
  sales_note?: string
  verification_evidence?: string[]
}

type Analysis = {
  id: number
  status: string
  document_name: string
  document_pages?: number
  created_at?: string
  key_points?: any
  excel_url?: string
  error?: string
  error_message?: string
}

const fieldOrder = [
  'tender_title',
  'tender_ref_no',
  'tender_due_date',
  'pre_bid_date',
  'scope_of_work',
  'eligibility_criteria',
  'technical_details',
  'delivery_period',
  'payment_terms',
  'ld_clause',
  'emd',
  'tender_fee',
  'pbg',
]

const fallbackTitles: Record<string, string> = {
  tender_title: 'Tender Title',
  tender_ref_no: 'Tender Ref No',
  tender_fee: 'Tender Fee',
  scope_of_work: 'Scope of Work',
  eligibility_criteria: 'Eligibility Criteria',
  technical_details: 'Technical Details',
  delivery_period: 'Delivery Period',
  payment_terms: 'Payment Terms',
  emd: 'EMD',
  pbg: 'PBG / Performance Bank Guarantee',
  ld_clause: 'LD Clause',
  tender_due_date: 'Tender Due Date',
  pre_bid_date: 'Pre-bid Date',
}

function pagesText(pages?: Array<number | string> | string) {
  if (!pages || (Array.isArray(pages) && pages.length === 0)) return 'Not available'
  return Array.isArray(pages) ? pages.join(', ') : pages
}

function cleanText(value: string, max = 1200) {
  const text = String(value || '').replace(/\s+/g, ' ').trim()
  return text.length > max ? `${text.slice(0, max).trim()}...` : text
}

function salesValueText(section: SalesSection) {
  const lines: string[] = []
  const add = (value?: any, max = 500) => {
    const text = cleanText(String(value || ''), max)
    if (!text || lines.includes(text)) return
    lines.push(text)
  }
  if (section.value) return String(section.value)

  if (Array.isArray(section.values) && section.values.length > 0) {
    section.values.filter(Boolean).forEach(v => add(v, 350))
    return lines.length === 1 ? lines[0] : lines.map(v => `• ${v}`).join("\n")
  }

  ;(section.key_values || []).filter(Boolean).forEach(v => add(v, 350))

  const answer = String(section.final_answer || section.answer || '').trim()
  if (answer && answer.toLowerCase() !== 'not found in extracted text') {
    if (answer.length <= 900) {
      answer.split(/\n+|\s*•\s*/).filter(Boolean).forEach(v => add(v, 350))
    } else if (lines.length === 0) {
      add(answer, 700)
    }
  }

  ;(section.details || []).filter(Boolean).slice(0, 8).forEach(v => add(v, 400))

  if (lines.length === 0) return 'Not found in extracted text'
  if (lines.length === 1) return lines[0]
  return lines.map(v => `• ${v}`).join('\n')
}

function normalizeLegacySection(key: string, kp: any): SalesSection | null {
  const flat = Array.isArray(kp?.fields) ? kp.fields.find((x: any) => x.key === key) : null
  if (flat) {
    return {
      title: flat.field || fallbackTitles[key] || key,
      value: flat.value || 'Not found in extracted text',
      pages: flat.page_ref || 'Not available',
    }
  }

  const modern = kp?.extracted_sections?.[key]
  if (modern) return modern

  // Backward compatibility for analyses generated by the older code.
  if (key === 'emd') {
    const emd = kp?.financial_requirements?.emd
    if (!emd) return null
    return {
      title: 'EMD',
      final_answer: [emd.amount, emd.percentage, emd.period_or_validity, emd.exemption].filter(Boolean).join(' · ') || 'Not found in extracted text',
      key_values: [emd.amount && `Amount: ${emd.amount}`, emd.percentage && `Percentage: ${emd.percentage}`, emd.period_or_validity && `Validity/Period: ${emd.period_or_validity}`, emd.exemption && `Exemption: ${emd.exemption}`].filter(Boolean) as string[],
      pages: emd.pages,
      confidence: emd.confidence,
      sales_note: 'Confirm EMD amount, mode and validity with finance before submission.',
    }
  }
  if (key === 'pbg') {
    const bg = kp?.financial_requirements?.bg
    if (!bg) return null
    return {
      title: 'PBG / Performance Bank Guarantee',
      final_answer: [bg.amount, bg.percentage, bg.period_or_validity, bg.claim_period].filter(Boolean).join(' · ') || 'Not found in extracted text',
      key_values: [bg.amount && `Amount: ${bg.amount}`, bg.percentage && `Percentage: ${bg.percentage}`, bg.period_or_validity && `Validity/Period: ${bg.period_or_validity}`, bg.claim_period && `Claim Period: ${bg.claim_period}`].filter(Boolean) as string[],
      pages: bg.pages,
      confidence: bg.confidence,
      sales_note: 'Confirm PBG percentage/validity because this affects commercial risk.',
    }
  }
  if (key === 'tender_due_date') {
    const due = kp?.important_dates?.tender_due_date
    if (!due) return null
    return {
      title: 'Tender Due Date',
      final_answer: [due.date, due.time].filter(Boolean).join(' ') || 'Not found in extracted text',
      key_values: [due.date && `Date: ${due.date}`, due.time && `Time: ${due.time}`].filter(Boolean) as string[],
      pages: due.pages,
      confidence: due.confidence,
      sales_note: 'Track this as a hard deadline in CRM.',
    }
  }
  if (key === 'pre_bid_date') {
    const pre = kp?.important_dates?.pre_bid_date
    if (!pre) return null
    return {
      title: 'Pre-bid Date',
      final_answer: [pre.date, pre.time, pre.venue_or_link].filter(Boolean).join(' · ') || 'Not found in extracted text',
      key_values: [pre.date && `Date: ${pre.date}`, pre.time && `Time: ${pre.time}`, pre.venue_or_link && `Venue/Link: ${pre.venue_or_link}`].filter(Boolean) as string[],
      pages: pre.pages,
      confidence: pre.confidence,
      sales_note: 'Attend or submit clarifications before this date.',
    }
  }
  const old = kp?.[key]
  if (!old) return null
  if (typeof old === 'string') {
    return { title: fallbackTitles[key], final_answer: old, key_values: [], details: [], pages: [], confidence: 'Low' }
  }
  return {
    title: fallbackTitles[key],
    final_answer: old.final_answer || old.answer || 'Not found in extracted text',
    key_values: old.key_values || [],
    details: old.details || [],
    pages: old.pages || [],
    confidence: old.confidence || 'Low',
    sales_note: old.sales_note || 'Verify with source pages before bid submission.',
  }
}

function SectionCard({ section, title }: { section: SalesSection; title: string }) {
  return (
    <tr className="border-b border-gray-100 align-top hover:bg-gray-50">
      <td className="w-72 px-4 py-4 text-sm font-semibold text-gray-900">{section.title || title}</td>
      <td className="px-4 py-4 text-sm leading-6 text-gray-800 whitespace-pre-wrap">{salesValueText(section)}</td>
      <td className="w-36 px-4 py-4 text-sm text-gray-600">{pagesText(section.pages)}</td>
    </tr>
  )
}


export default function RFPPage() {
  const { label: rfpLabel, singular: rfpSingular } = useModuleName('rfp')
  const [analyses, setAnalyses] = useState<Analysis[]>([])
  const [keywords, setKeywords] = useState<Keyword[]>([])
  const [loading, setLoading] = useState(true)
  const [uploading, setUploading] = useState(false)
  const [expanded, setExpanded] = useState<number | null>(null)
  const [file, setFile] = useState<File | null>(null)
  const [showKeywordPanel, setShowKeywordPanel] = useState(false)
  const [newKeyword, setNewKeyword] = useState('')
  const [newAliases, setNewAliases] = useState('')
  const [oneTimeKeywords, setOneTimeKeywords] = useState('')
  const { success, error: showError } = useToast()

  const activeKeywordCount = useMemo(() => keywords.filter(k => k.active).length, [keywords])

  const load = async (passive = false) => {
    setLoading(true)
    try {
      const passiveConfig = passive ? withPassiveSessionActivity({}) : undefined
      const [analysisRes, keywordRes] = await Promise.all([
        api.get('/rfp', passiveConfig),
        api.get('/rfp/keywords', passiveConfig),
      ])
      setAnalyses(analysisRes.data || [])
      setKeywords(keywordRes.data || [])
    } catch {
      showError('Failed to load RFP analysis data')
    } finally {
      setLoading(false)
    }
  }

  useEffect(() => { load() }, [])

  // Poll while any analysis is still Processing. Backend now queues the heavy
  // PDF + Ollama work in the background so the CRM server stays responsive.
  useEffect(() => {
    const hasProcessing = analyses.some(a => a.status === 'Processing')
    if (!hasProcessing) return
    const timer = window.setInterval(() => { load(true) }, 5000)
    return () => window.clearInterval(timer)
  }, [analyses])

  const addKeyword = async () => {
    const name = newKeyword.trim()
    if (!name) return showError('Enter a keyword name')
    try {
      await api.post('/rfp/keywords', {
        name,
        aliases: newAliases.split(',').map(x => x.trim()).filter(Boolean),
        category: 'Custom',
        prompt_hint: `Extract the final sales-useful answer for ${name}, including amount/date/period/condition and page reference if available.`,
        active: true,
      })
      success('Keyword added. It will be included from the next analysis.')
      setNewKeyword('')
      setNewAliases('')
      load()
    } catch (e: any) {
      showError(e.response?.data?.detail || 'Failed to add keyword')
    }
  }

  const deleteKeyword = async (keyword: Keyword) => {
    if (keyword.is_default) return showError('Default keywords cannot be deleted')
    try {
      await api.delete(`/rfp/keywords/${keyword.key}`)
      success('Keyword removed')
      load()
    } catch (e: any) {
      showError(e.response?.data?.detail || 'Failed to delete keyword')
    }
  }

  const handleFileSelection = (selectedFile: File) => {
    const isPdf = selectedFile.type === 'application/pdf' || selectedFile.name.toLowerCase().endsWith('.pdf')
    if (!isPdf) {
      showError('Please choose a PDF file')
      return
    }
    setFile(selectedFile)
  }

  const handleUpload = async () => {
    if (!file) return showError('Please select a PDF file')
    setUploading(true)
    try {
      const fd = new FormData()
      fd.append('file', file)
      if (oneTimeKeywords.trim()) fd.append('extra_keywords', oneTimeKeywords.trim())
      const r = await api.post('/rfp/analyze', fd, { headers: { 'Content-Type': 'multipart/form-data' } })
      success('RFP analysis completed/queued. Excel will be available when status becomes Completed.')
      setFile(null)
      setOneTimeKeywords('')
      await load()
      if (r.data?.id) setExpanded(r.data.id)
    } catch (e: any) {
      showError(e.response?.data?.detail || 'Analysis failed')
    } finally {
      setUploading(false)
    }
  }

  const statusIcon = (status: string) => {
    if (status === 'Completed') return <CheckCircle size={16} className="text-green-500" />
    if (status === 'Failed') return <AlertCircle size={16} className="text-red-500" />
    return <Brain size={16} className="animate-pulse text-purple-500" />
  }

  const excelHref = (a: Analysis) => a.excel_url || a.key_points?.excel_url || `/api/rfp/${a.id}/excel`

  const renderAnalysis = (a: Analysis) => {
    const kp = a.key_points || {}
    const salesSummary = kp.sales_summary || {}
    const sections = fieldOrder
      .map(key => [key, normalizeLegacySection(key, kp)] as [string, SalesSection | null])
      .filter(([, section]) => Boolean(section)) as [string, SalesSection][]
    const flatCustomSections = Array.isArray(kp?.fields)
      ? kp.fields
          .filter((x: any) => x?.key && !fieldOrder.includes(x.key))
          .map((x: any) => [x.key, { title: x.field || x.key, value: x.value, pages: x.page_ref }] as [string, SalesSection])
      : []
    const customSections = [
      ...flatCustomSections,
      ...(Object.entries(kp.custom_keyword_results || {}) as [string, SalesSection][]),
    ]

    return (
      <div className="space-y-5 border-t border-gray-100 px-4 pb-4 pt-4">
        <div className="grid grid-cols-1 gap-4 xl:grid-cols-3">
          <div className="rounded-2xl bg-indigo-50 p-5 xl:col-span-2">
            <div className="flex items-start gap-3">
              <Target size={20} className="mt-0.5 text-indigo-600" />
              <div>
                <p className="text-xs font-semibold uppercase tracking-wide text-indigo-500">Tender Overview</p>
                <p className="mt-2 text-sm leading-6 text-gray-800">{kp.tender_overview || 'No overview extracted'}</p>
                {kp.buyer_department && <p className="mt-2 text-xs text-gray-500">Buyer / Department: {kp.buyer_department}</p>}
              </div>
            </div>
          </div>
          <div className="rounded-2xl bg-green-50 p-5">
            <p className="text-xs font-semibold uppercase tracking-wide text-green-600">Sales Decision Summary</p>
            <p className="mt-2 text-sm leading-6 text-gray-800">{salesSummary.bid_decision_summary || 'Review extracted fields before bid/no-bid decision.'}</p>
            {a.status === 'Completed' && (
              <a href={excelHref(a)} target="_blank" rel="noreferrer" className="mt-4 inline-flex items-center gap-2 rounded-lg bg-green-600 px-3 py-2 text-sm font-medium text-white hover:bg-green-700">
                <Download size={16} /> Download Sales Excel
              </a>
            )}
          </div>
        </div>

        {Array.isArray(salesSummary.commercial_alerts) && salesSummary.commercial_alerts.length > 0 && (
          <div className="rounded-2xl border border-amber-200 bg-amber-50 p-4">
            <div className="mb-2 flex items-center gap-2">
              <ShieldAlert size={18} className="text-amber-600" />
              <h4 className="text-sm font-semibold text-amber-900">Commercial Alerts</h4>
            </div>
            <ul className="space-y-1 text-sm leading-6 text-amber-900">
              {salesSummary.commercial_alerts.map((item: string, idx: number) => <li key={idx}>• {item}</li>)}
            </ul>
          </div>
        )}

        <div className="overflow-hidden rounded-2xl border border-gray-100 bg-white shadow-sm">
          <table className="w-full table-fixed border-collapse">
            <thead className="bg-gray-900 text-white">
              <tr>
                <th className="w-72 px-4 py-3 text-left text-xs font-semibold uppercase tracking-wide">Field</th>
                <th className="px-4 py-3 text-left text-xs font-semibold uppercase tracking-wide">Values</th>
                <th className="w-36 px-4 py-3 text-left text-xs font-semibold uppercase tracking-wide">Page Ref</th>
              </tr>
            </thead>
            <tbody>
              {sections.map(([key, section]) => <SectionCard key={key} title={fallbackTitles[key] || key} section={section} />)}
              {customSections.map(([key, section]) => <SectionCard key={key} title={section.title || key} section={section} />)}
            </tbody>
          </table>
        </div>

        {Array.isArray(salesSummary.recommended_next_actions) && salesSummary.recommended_next_actions.length > 0 && (
          <div className="rounded-2xl border border-gray-100 bg-white p-4 shadow-sm">
            <h4 className="mb-2 text-sm font-semibold text-gray-900">Recommended Next Actions</h4>
            <ul className="space-y-1 text-sm leading-6 text-gray-700">
              {salesSummary.recommended_next_actions.map((item: string, idx: number) => <li key={idx}>• {item}</li>)}
            </ul>
          </div>
        )}
      </div>
    )
  }

  return (
    <div className="p-6">
      <PageHeader
        title={`Sales ${rfpLabel}`}
        subtitle="Updated V4: extracts clean sales-ready tender values in Field / Values / Page Ref format"
        breadcrumb={['Tenders', rfpLabel]}
        actions={<button onClick={() => load()} className="p-1.5 rounded-lg border border-gray-200 bg-white hover:bg-gray-50 text-gray-400 hover:text-gray-600 transition-colors"><RefreshCw size={13} className={loading ? 'animate-spin' : ''} /></button>}
      />

      <div className="mb-6 grid grid-cols-1 gap-4 xl:grid-cols-3">
        <Card className="xl:col-span-2">
          <div className="p-2">
            <div className="rounded-2xl border border-purple-100 bg-gradient-to-r from-purple-50 to-indigo-50 p-5">
              <div className="flex items-start gap-4">
                <div className="rounded-xl bg-purple-100 p-3"><Brain size={24} className="text-purple-600" /></div>
                <div className="flex-1">
                  <h3 className="font-semibold text-gray-900">Analyze RFP / Tender PDF</h3>
                  <p className="mt-1 text-sm text-gray-600">Creates a clean Field / Values / Page Ref report for scope, eligibility, technical details, EMD, PBG, delivery, LD, payment terms, tender due date and pre-bid date.</p>

                  <div className="mt-4 space-y-3">
                    <DropFileUpload
                      label="Drop tender PDF here, or click to browse"
                      file={file}
                      accept=".pdf,application/pdf"
                      variant="panel"
                      uploading={uploading}
                      helperText={file ? 'Ready to queue for AI analysis.' : 'Drag and drop a tender PDF from your desktop or browse manually.'}
                      className="border-purple-200 bg-white text-gray-600 hover:border-purple-300 hover:bg-purple-50/70"
                      onFile={handleFileSelection}
                    />
                    {file && (
                      <Button onClick={handleUpload} loading={uploading} leftIcon={<FileSpreadsheet size={16} />} className="bg-purple-600 text-white hover:bg-purple-700">
                        {uploading ? 'Queuing…' : 'Analyse & Generate Sales Excel'}
                      </Button>
                    )}
                    {file && <button onClick={() => setFile(null)} className="text-sm text-gray-400 hover:text-gray-600">Clear</button>}
                  </div>

                  <div className="mt-4">
                    <label className="mb-1 block text-xs font-semibold uppercase tracking-wide text-gray-500">One-time extra fields for this upload</label>
                    <input
                      value={oneTimeKeywords}
                      onChange={e => setOneTimeKeywords(e.target.value)}
                      placeholder="Example: warranty, SLA, training, AMC"
                      className="w-full rounded-lg border border-gray-200 bg-white px-3 py-2 text-sm outline-none focus:border-purple-400 focus:ring-2 focus:ring-purple-100"
                    />
                    <p className="mt-1 text-xs text-gray-400">Permanent fields can be added in the Keyword Library.</p>
                  </div>
                </div>
              </div>
            </div>
          </div>
        </Card>

        <Card>
          <div className="p-5">
            <div className="flex items-center justify-between">
              <div>
                <p className="text-xs font-semibold uppercase tracking-wide text-gray-500">Extraction Field Library</p>
                <h3 className="mt-1 text-2xl font-bold text-gray-900">{activeKeywordCount}</h3>
                <p className="text-sm text-gray-500">active fields</p>
              </div>
              <button onClick={() => setShowKeywordPanel(v => !v)} className="rounded-lg border border-gray-200 p-2 text-gray-600 hover:bg-gray-50">
                {showKeywordPanel ? <ChevronUp size={18} /> : <ChevronDown size={18} />}
              </button>
            </div>
            {showKeywordPanel && (
              <div className="mt-4 space-y-3">
                <input value={newKeyword} onChange={e => setNewKeyword(e.target.value)} placeholder="New extraction field" className="w-full rounded-lg border border-gray-200 px-3 py-2 text-sm outline-none focus:border-blue-400" />
                <input value={newAliases} onChange={e => setNewAliases(e.target.value)} placeholder="Aliases, comma separated" className="w-full rounded-lg border border-gray-200 px-3 py-2 text-sm outline-none focus:border-blue-400" />
                <Button onClick={addKeyword} leftIcon={<Plus size={16} />} className="w-full bg-blue-600 text-white hover:bg-blue-700">Add Field</Button>
                <div className="max-h-64 space-y-2 overflow-auto pr-1">
                  {keywords.map(k => (
                    <div key={k.key} className="flex items-center justify-between rounded-lg bg-gray-50 px-3 py-2">
                      <div>
                        <p className="text-sm font-medium text-gray-900">{k.name}</p>
                        <p className="text-xs text-gray-400">{k.category}{k.is_default ? ' · default' : ''}</p>
                      </div>
                      {!k.is_default && <button onClick={() => deleteKeyword(k)} className="text-gray-400 hover:text-red-600"><Trash2 size={15} /></button>}
                    </div>
                  ))}
                </div>
              </div>
            )}
          </div>
        </Card>
      </div>

      <div className="space-y-3">
        {loading ? (
          <Card><div className="p-12 text-center text-gray-400">Loading...</div></Card>
        ) : analyses.length === 0 ? (
          <Card><div className="p-12 text-center"><Brain size={48} className="mx-auto mb-3 text-gray-200" /><p className="font-medium text-gray-500">No analyses yet</p><p className="mt-1 text-sm text-gray-400">Upload your first RFP document above</p></div></Card>
        ) : analyses.map(a => (
          <Card key={a.id}>
            <div className="flex cursor-pointer items-center justify-between rounded-xl p-4 transition-colors hover:bg-gray-50" onClick={() => setExpanded(expanded === a.id ? null : a.id)}>
              <div className="flex items-center gap-3">
                {statusIcon(a.status)}
                <div>
                  <p className="text-sm font-semibold text-gray-900">{a.document_name}</p>
                  <p className="text-xs text-gray-400">{a.document_pages ? `${a.document_pages} pages` : 'RFP analysis'}</p>
                </div>
              </div>
              <div className="flex items-center gap-3">
                {a.status === 'Completed' && <a onClick={e => e.stopPropagation()} href={excelHref(a)} target="_blank" rel="noreferrer" className="hidden items-center gap-1 rounded-lg bg-green-50 px-3 py-1.5 text-xs font-medium text-green-700 hover:bg-green-100 sm:flex"><Download size={14} /> Excel</a>}
                <span className={`rounded-full px-2 py-0.5 text-xs font-medium ${a.status === 'Completed' ? 'bg-green-100 text-green-700' : a.status === 'Failed' ? 'bg-red-100 text-red-700' : 'bg-purple-100 text-purple-700'}`}>{a.status}</span>
                {expanded === a.id ? <ChevronUp size={16} className="text-gray-400" /> : <ChevronDown size={16} className="text-gray-400" />}
              </div>
            </div>
            {expanded === a.id && a.status === 'Completed' && renderAnalysis(a)}
            {expanded === a.id && a.status === 'Processing' && (
              <div className="border-t border-gray-100 px-4 pb-4 pt-4">
                <div className="rounded-lg border border-purple-200 bg-purple-50 p-3 text-sm text-purple-700">
                  RFP extraction is running. You can continue using CRM. This page refreshes automatically.
                </div>
              </div>
            )}
            {expanded === a.id && (a.error_message || a.error) && (
              <div className="border-t border-gray-100 px-4 pb-4 pt-4"><div className="rounded-lg border border-red-200 bg-red-50 p-3 text-sm text-red-700"><strong>Error:</strong> {a.error_message || a.error}</div></div>
            )}
          </Card>
        ))}
      </div>
    </div>
  )
}
